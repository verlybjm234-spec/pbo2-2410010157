private double totalAkhir = 0;

private void simpanData() {
    String npm = txtNpm.getText().trim();
    String nama = txtNama.getText().trim();

    if (!npm.matches("\\d{10}")) {
        lblError.setText("NPM harus 10 digit angka");
        txtNpm.setBorder(BorderFactory.createLineBorder(Color.RED));
        return;
    }
    txtNpm.setBorder(null);

    if (nama.isEmpty()) {
        lblError.setText("Nama tidak boleh kosong");
        return;
    }

    double tugas, uts, uas;
    try {
        tugas = Double.parseDouble(txtTugas.getText().trim());
        uts = Double.parseDouble(txtUts.getText().trim());
        uas = Double.parseDouble(txtUas.getText().trim());
    } catch (NumberFormatException e) {
        lblError.setText("Nilai harus berupa angka");
        return;
    }

    if (!nilaiValid(tugas) || !nilaiValid(uts) || !nilaiValid(uas)) {
        lblError.setText("Nilai harus 0 sampai 100");
        return;
    }

    double akhir = 0.3 * tugas + 0.3 * uts + 0.4 * uas;

    DefaultTableModel model = (DefaultTableModel) tblNilai.getModel();
    model.addRow(new Object[]{
        npm, nama, (int) tugas, (int) uts, (int) uas,
        String.format(Locale.forLanguageTag("id-ID"), "%.2f", akhir),
        hitungHuruf(akhir)
    });

    totalAkhir += akhir;
    lblError.setText("");
    kosongkanInput();
    updateRingkasan();
}

private boolean nilaiValid(double n) {
    return n >= 0 && n <= 100;
}

private String hitungHuruf(double n) {
    if (n >= 80) return "A";
    if (n >= 70) return "B";
    if (n >= 60) return "C";
    if (n >= 50) return "D";
    return "E";
}

private void kosongkanInput() {
    txtNpm.setText("");
    txtNama.setText("");
    txtTugas.setText("");
    txtUts.setText("");
    txtUas.setText("");
    txtNpm.requestFocus();
}

private void updateRingkasan() {
    int jumlah = tblNilai.getRowCount();
    double rata = jumlah == 0 ? 0 : totalAkhir / jumlah;
    lblRingkasan.setText(String.format(Locale.forLanguageTag("id-ID"),
            "Jumlah mahasiswa: %d, rata-rata nilai akhir: %.2f", jumlah, rata));
}
    

